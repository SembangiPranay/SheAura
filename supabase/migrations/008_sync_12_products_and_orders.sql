-- 1. Ensure 'orders' table exists with complete schema
create table if not exists public.orders (
  id text primary key,
  user_id text,
  client_name text,
  client_email text,
  client_phone text,
  shipping_address jsonb,
  items jsonb not null default '[]'::jsonb,
  items_count integer default 1,
  total_amount text not null,
  subtotal numeric,
  payment_method text default 'upi',
  status text not null default 'processing',
  tracking_number text,
  eta text,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 2. Configure Row Level Security (RLS) on 'orders'
alter table public.orders enable row level security;

drop policy if exists "allow_public_orders_insert" on public.orders;
create policy "allow_public_orders_insert"
  on public.orders for insert
  with check (true);

drop policy if exists "allow_public_orders_select" on public.orders;
create policy "allow_public_orders_select"
  on public.orders for select
  using (true);

drop policy if exists "allow_public_orders_update" on public.orders;
create policy "allow_public_orders_update"
  on public.orders for update
  using (true);

-- 3. Ensure 'products' table has resilient policies for dynamic testing & management
alter table public.products enable row level security;

drop policy if exists "public select published products" on public.products;
create policy "public select published products"
  on public.products for select
  using (is_published = true or auth.role() = 'authenticated');

drop policy if exists "allow_admin_manage_products" on public.products;
create policy "allow_admin_manage_products"
  on public.products for all
  using (true)
  with check (true);

